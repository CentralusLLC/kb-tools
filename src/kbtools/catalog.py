"""Catalog: one record per knowledge page, for orientation (docs/catalog.md) and filtering.

The committed catalog holds only fields that change when pages change (no ages or
time-based flags), so it never drifts on its own. Filtered queries are produced on
demand from front matter, so no JSON copy is stored.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import okf
from .common import Repo, atomic_write
from .report import page_trust

CATALOG = "catalog.md"
START, END = "<!-- kb:catalog:start -->", "<!-- kb:catalog:end -->"
HEADER = """---
type: Catalog
title: Catalog
description: Generated list of every page in this knowledge base with its type, description, tags and trust; read it first to find pages.
tags: [catalog, index]
status: stable
---

# Catalog

Every page in this knowledge base, one line each, grouped by section. Generated by
`tools/kb catalog --write` (do not edit between the markers). For filtered or
machine-readable output, run `tools/kb catalog --type ... --tier ... --format jsonl`.
Trust is the verification level (human, machine, unverified) and the last
verification date; see the conventions page.

"""


def records(repo: Repo) -> list[dict]:
    trust = {row["page"]: row for row in page_trust(repo, max_age_days=365)}
    out = []
    for path in okf.bundle_pages(repo.docs):
        relative = path.relative_to(repo.docs).as_posix()
        if not okf.is_concept(path) or relative == CATALOG:
            continue
        data, _, error = okf.parse_front_matter(path.read_text(encoding="utf-8", errors="replace"))
        if error or data is None or okf.is_template(data):
            continue
        row = trust.get(repo.rel(path), {})
        tags = data.get("tags") or []
        out.append({
            "path": relative,
            "section": relative.split("/")[0] if "/" in relative else "",
            "type": str(data.get("type", "")),
            "title": str(data.get("title", "") or Path(relative).stem),
            "description": " ".join(str(data.get("description", "")).split()),
            "tags": [str(t) for t in tags] if isinstance(tags, list) else [str(tags)],
            "status": str(data.get("status", "stable")),
            "work_status": str(data.get("work_status", "")),
            "id": str(data.get("id", "")),
            "tier": row.get("tier", "unverified"),
            "last_verified": row.get("last_verified", ""),
            "flags": row.get("flags", ""),
        })
    return out


def select(rows: list[dict], *, type_: str | None = None, section: str | None = None, tag: str | None = None,
           tier: str | None = None, status: str | None = None, work_status: str | None = None,
           text: str | None = None) -> list[dict]:
    def keep(r: dict) -> bool:
        if type_ and r["type"].lower() != type_.lower():
            return False
        if section and r["section"] != section.strip("/"):
            return False
        if tag and tag not in r["tags"]:
            return False
        if tier and r["tier"] != tier:
            return False
        if status and r["status"] != status:
            return False
        if work_status and r["work_status"] != work_status:
            return False
        if text:
            haystack = " ".join([r["path"], r["title"], r["description"], " ".join(r["tags"])]).lower()
            if not all(word in haystack for word in text.lower().split()):
                return False
        return True

    return [r for r in rows if keep(r)]


def _cell(value: str) -> str:
    return value.replace("|", "\\|")


def markdown(rows: list[dict], link_base: str = "") -> str:
    if not rows:
        return "_No pages._\n"
    sections: dict[str, list[dict]] = {}
    for r in rows:
        sections.setdefault(r["section"], []).append(r)
    out = []
    for name in sorted(sections, key=lambda s: (s != "", s)):
        out += [f"## {name + '/' if name else 'Root'}", "",
                "| Page | Type | Description | Tags | Status | Trust |", "| --- | --- | --- | --- | --- | --- |"]
        for r in sections[name]:
            label = f"{r['id']} {r['title']}".strip() if r["id"] and r["id"] not in r["title"] else r["title"]
            status = r["status"] + (f", {r['work_status']}" if r["work_status"] else "")
            trust = r["tier"] + (f" {r['last_verified']}" if r["last_verified"] else "")
            out.append(f"| [{_cell(label)}]({link_base}{r['path']}) | {r['type']} | {_cell(r['description'])} | "
                       f"{', '.join(r['tags'])} | {status} | {trust} |")
        out.append("")
    return "\n".join(out)


def render(rows: list[dict], fmt: str) -> str:
    if fmt == "json":
        return json.dumps(rows, indent=2) + "\n"
    if fmt == "jsonl":
        return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)
    return markdown(rows)


def expected(repo: Repo, current: str | None) -> str:
    block = f"{START}\n{markdown(records(repo))}{END}"
    if current and START in current and END in current:
        before, rest = current.split(START, 1)
        _, after = rest.split(END, 1)
        return before + block + after
    return HEADER + block + "\n"


def write(repo: Repo) -> Path:
    path = repo.docs / CATALOG
    current = path.read_text(encoding="utf-8") if path.exists() else None
    atomic_write(path, expected(repo, current))
    return path


def is_stale(repo: Repo) -> bool | None:
    """None when there is no catalog, else whether it differs from a fresh one."""
    path = repo.docs / CATALOG
    if not path.exists():
        return None
    current = path.read_text(encoding="utf-8")
    return current != expected(repo, current)


def refresh_if_present(repo: Repo) -> None:
    if (repo.docs / CATALOG).exists():
        write(repo)
